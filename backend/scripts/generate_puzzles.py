"""Generate blindfold-friendly puzzles without the Lichess database (fallback).

Usage (from ``backend/``)::

    uv run python scripts/generate_puzzles.py                 # Stockfish if found
    uv run python scripts/generate_puzzles.py --no-engine     # pure Python, mates only

Candidates are random sparse positions (3-9 pieces) where the opponent is to
move; a random opponent move is played as the Lichess-style setup move, then:

* with Stockfish: the engine screens the solver's position (multipv 2). Forced
  mates in 1-3 are confirmed and turned into a line by the pure-Python search
  (Stockfish can miss short sacrificial mates at high depth, so it is never the
  final word); a single clearly winning move (best >= +3, runner-up much worse,
  balanced before the setup move) becomes a one-move ``win`` puzzle.
* without an engine: the pure-Python mate search alone (mate goals only).

Mate lines must be unique: one key move, one way to continue (several mating
moves are tolerated only on the last move of a longer line), and the defender
always plays the reply that delays mate the longest. Ratings are estimates.
"""

from __future__ import annotations

import argparse
import hashlib
import logging
import random
import shutil
import sys
import time
from collections import Counter
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Final

import chess
import chess.engine

from matesearch import MateSearch, SearchLimitError
from puzzlelib import (
    MATE_GOAL_BY_LENGTH,
    Goal,
    PuzzleEntry,
    check_line,
    clean_themes,
    fit_sample,
    goal_for,
    stratified_sample,
    summarize,
    today,
    write_puzzle_file,
)

LOG = logging.getLogger("generate_puzzles")

BACKEND_DIR: Final = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT: Final = BACKEND_DIR / "app" / "data" / "puzzles.json"
DEFAULT_FRONTEND_OUTPUT: Final = BACKEND_DIR.parent / "frontend" / "public" / "data" / "puzzles.json"
GENERATED_SOURCE: Final = "Generated by scripts/generate_puzzles.py (Blindfold Chess), CC0"
ENGINE_LOCATIONS: Final = ("/usr/games/stockfish", "/usr/bin/stockfish", "/usr/local/bin/stockfish")

# Solver material is drawn from the first pool, the opponent's from the second.
ATTACKER_POOL: Final = (
    chess.QUEEN,
    chess.QUEEN,
    chess.ROOK,
    chess.ROOK,
    chess.ROOK,
    chess.BISHOP,
    chess.KNIGHT,
    chess.PAWN,
    chess.PAWN,
)
DEFENDER_POOL: Final = (chess.PAWN, chess.PAWN, chess.PAWN, chess.KNIGHT, chess.BISHOP, chess.ROOK)
BASE_RATING: Final[dict[Goal, int]] = {"mate1": 900, "mate2": 1400, "mate3": 1800, "win": 1500}
WIN_THRESHOLD: Final = 300
WIN_MARGIN: Final = 300
BALANCED_LIMIT: Final = 100
ENGINE_DEPTH: Final = 12
DEFAULT_NODE_LIMIT: Final = 200_000
DEFAULT_TIME_BUDGET: Final = 600.0


@dataclass(frozen=True, slots=True)
class GeneratorConfig:
    max_mate: int = 3
    node_limit: int = DEFAULT_NODE_LIMIT
    time_budget: float = DEFAULT_TIME_BUDGET
    setup_tries: int = 3


def find_engine(explicit: str | None) -> str | None:
    """Explicit path or command, then ``PATH``, then the usual install locations."""
    if explicit:
        return explicit if Path(explicit).is_file() else shutil.which(explicit)
    found = shutil.which("stockfish")
    if found:
        return found
    return next((path for path in ENGINE_LOCATIONS if Path(path).is_file()), None)


def random_setup_position(rng: random.Random) -> chess.Board:
    """A random legal sparse position; the side to move is the *opponent*."""
    while True:
        opponent = rng.choice(chess.COLORS)
        solver = not opponent
        board = chess.Board.empty()
        squares = list(chess.SQUARES)
        rng.shuffle(squares)
        pieces = [(chess.KING, solver), (chess.KING, opponent)]
        pieces += [(rng.choice(ATTACKER_POOL), solver) for _ in range(rng.randint(1, 3))]
        pieces += [(rng.choice(DEFENDER_POOL), opponent) for _ in range(rng.randint(0, 4))]
        for piece_type, color in pieces:
            square = next(sq for sq in squares if piece_type != chess.PAWN or 1 <= chess.square_rank(sq) <= 6)
            squares.remove(square)
            board.set_piece_at(square, chess.Piece(piece_type, color))
        board.turn = opponent
        if board.is_valid() and not board.is_game_over():
            return board


def build_mate_line(search: MateSearch, board: chess.Board, length: int) -> list[chess.Move] | None:
    """Solver to move with a shortest mate in ``length``: the unique solution line."""
    board = board.copy(stack=False)
    line: list[chess.Move] = []
    for remaining in range(length, 0, -1):
        candidates = search.mating_moves(board, remaining)
        final_of_longer_line = remaining == 1 and length > 1
        if not candidates or (len(candidates) > 1 and not final_of_longer_line):
            return None
        move = candidates[0]
        board.push(move)
        line.append(move)
        if board.is_checkmate():
            return line if remaining == 1 else None
        defence = search.best_defence(board, remaining - 1)
        if defence is None:
            return None
        board.push(defence)
        line.append(defence)
    return None


def estimate_rating(goal: Goal, pieces: int, legal_moves: int) -> int:
    rating = BASE_RATING[goal] + 15 * (pieces - 5) + 5 * (legal_moves - 20)
    return max(600, min(2400, rating))


def make_entry(
    start: chess.Board, moves: Sequence[chess.Move], goal: Goal, extra_themes: Sequence[str]
) -> PuzzleEntry | None:
    """Verify the line with the shared checker and wrap it as a puzzle entry."""
    ucis = [move.uci() for move in moves]
    fen = start.fen()
    themes = [*extra_themes, "endgame"]
    if goal != "win":
        themes.append(f"mateIn{goal[-1]}")
    line = check_line(fen, ucis)
    if line is None or goal_for(themes, line) != goal:
        return None
    solver = start.copy(stack=False)
    solver.push(moves[0])
    digest = hashlib.blake2b(f"{fen}|{' '.join(ucis)}".encode(), digest_size=4).hexdigest()
    return PuzzleEntry(
        id=f"g{digest}",
        fen=fen,
        moves=tuple(ucis),
        rating=estimate_rating(goal, line.pieces, solver.legal_moves.count()),
        themes=clean_themes(themes, goal),
        pieces=line.pieces,
        goal=goal,
    )


def _solver_cp(score: chess.engine.PovScore, solver: chess.Color) -> int:
    return score.pov(solver).score(mate_score=100_000)


class Generator:
    def __init__(
        self,
        rng: random.Random,
        config: GeneratorConfig,
        engine: chess.engine.SimpleEngine | None,
    ) -> None:
        self.rng = rng
        self.config = config
        self.engine = engine
        self.stats: Counter[str] = Counter()

    def goals(self) -> tuple[Goal, ...]:
        mates = tuple(MATE_GOAL_BY_LENGTH[n] for n in range(1, self.config.max_mate + 1))
        return (*mates, "win") if self.engine is not None else mates

    def candidate(self) -> PuzzleEntry | None:
        start = random_setup_position(self.rng)
        setups = sorted(start.legal_moves, key=lambda move: move.uci())
        self.rng.shuffle(setups)
        for setup in setups[: self.config.setup_tries]:
            solver_board = start.copy(stack=False)
            solver_board.push(setup)
            if solver_board.is_game_over():
                continue
            self.stats["positions"] += 1
            try:
                entry = self._classify(start, setup, solver_board)
            except SearchLimitError:
                self.stats["node_limit"] += 1
                continue
            if entry is not None:
                return entry
        return None

    def _mate_entry(self, start: chess.Board, setup: chess.Move, board: chess.Board) -> PuzzleEntry | None:
        search = MateSearch(node_limit=self.config.node_limit)
        length = search.shortest_mate(board, self.config.max_mate)
        if length is None:
            return None
        line = build_mate_line(search, board, length)
        if line is None:
            self.stats["ambiguous"] += 1
            return None
        return make_entry(start, [setup, *line], MATE_GOAL_BY_LENGTH[length], [])

    def _classify(self, start: chess.Board, setup: chess.Move, board: chess.Board) -> PuzzleEntry | None:
        if self.engine is None:
            return self._mate_entry(start, setup, board)
        solver = board.turn
        infos = self.engine.analyse(board, chess.engine.Limit(depth=ENGINE_DEPTH), multipv=2)
        if not infos or "score" not in infos[0] or not infos[0].get("pv"):
            return None
        best = infos[0]["score"].pov(solver)
        mate = best.mate()
        if mate is not None and 0 < mate <= self.config.max_mate:
            return self._mate_entry(start, setup, board)
        best_cp = _solver_cp(infos[0]["score"], solver)
        if best_cp < WIN_THRESHOLD:
            return None
        if len(infos) > 1 and "score" in infos[1]:
            second = _solver_cp(infos[1]["score"], solver)
            if second > BALANCED_LIMIT or best_cp - second < WIN_MARGIN:
                return None
        before = self.engine.analyse(start, chess.engine.Limit(depth=ENGINE_DEPTH))
        if "score" not in before or _solver_cp(before["score"], solver) > BALANCED_LIMIT:
            return None
        theme = "crushing" if best_cp >= 2 * WIN_THRESHOLD else "advantage"
        return make_entry(start, [setup, infos[0]["pv"][0]], "win", [theme])

    def run(self, per_goal: int) -> list[PuzzleEntry]:
        found: dict[str, PuzzleEntry] = {}
        counts: Counter[str] = Counter()
        goals = self.goals()
        deadline = time.monotonic() + self.config.time_budget
        last_report = time.monotonic()
        while time.monotonic() < deadline and any(counts[goal] < per_goal for goal in goals):
            entry = self.candidate()
            if entry is None or entry.id in found or counts[entry.goal] >= per_goal:
                continue
            found[entry.id] = entry
            counts[entry.goal] += 1
            if time.monotonic() - last_report > 10:
                last_report = time.monotonic()
                LOG.info("found %s (%s)", dict(counts), dict(self.stats))
        if any(counts[goal] < per_goal for goal in goals):
            LOG.warning("time budget exhausted: %s of %d per goal", dict(counts), per_goal)
        return list(found.values())


def _parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--count", type=int, default=400, help="backend puzzles (spread over goals)")
    parser.add_argument("--frontend-count", type=int, default=200, help="frontend subset size")
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--engine", help="Stockfish binary (default: auto-discovery)")
    parser.add_argument("--no-engine", action="store_true", help="pure-Python mate search only")
    parser.add_argument("--max-mate", type=int, default=3, choices=(1, 2, 3))
    parser.add_argument("--node-limit", type=int, default=DEFAULT_NODE_LIMIT)
    parser.add_argument("--time-budget", type=float, default=DEFAULT_TIME_BUDGET, help="seconds")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--frontend-output", type=Path, default=DEFAULT_FRONTEND_OUTPUT)
    parser.add_argument("--no-frontend", action="store_true")
    parser.add_argument("--frontend-max-kb", type=int, default=245, help="1 KB = 1000 bytes")
    parser.add_argument("--generated", default=None, help="date stamp (default: today)")
    parser.add_argument("-v", "--verbose", action="store_true")
    return parser.parse_args(argv)


def generate(
    count: int,
    *,
    seed: int,
    engine_path: str | None,
    config: GeneratorConfig,
) -> list[PuzzleEntry]:
    """Generate up to ``count`` puzzles, balanced over the available goals."""
    rng = random.Random(seed)
    engine = chess.engine.SimpleEngine.popen_uci(engine_path) if engine_path else None
    try:
        if engine is not None:
            engine.configure({"Threads": 1, "Hash": 32})
        generator = Generator(rng, config, engine)
        per_goal = -(-count // len(generator.goals()))
        entries = generator.run(per_goal)
        LOG.info("generator stats: %s", dict(generator.stats))
    finally:
        if engine is not None:
            engine.quit()
    return stratified_sample(entries, count, seed)


def main(argv: Sequence[str] | None = None) -> int:
    args = _parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )
    engine_path = None if args.no_engine else find_engine(args.engine)
    LOG.info("engine: %s", engine_path or "none (pure-Python mate search)")
    config = GeneratorConfig(max_mate=args.max_mate, node_limit=args.node_limit, time_budget=args.time_budget)
    entries = generate(args.count, seed=args.seed, engine_path=engine_path, config=config)
    if not entries:
        LOG.error("no puzzle generated")
        return 1
    generated = args.generated or today()
    size = write_puzzle_file(args.output, entries, source=GENERATED_SOURCE, generated=generated)
    LOG.info("wrote %s (%.1f KB)\n%s", args.output, size / 1000, summarize(entries))
    if not args.no_frontend:
        subset = fit_sample(
            entries,
            args.frontend_count,
            args.seed,
            max_bytes=args.frontend_max_kb * 1000,
            source=GENERATED_SOURCE,
            generated=generated,
        )
        size = write_puzzle_file(args.frontend_output, subset, source=GENERATED_SOURCE, generated=generated)
        LOG.info("wrote %s (%.1f KB)\n%s", args.frontend_output, size / 1000, summarize(subset))
    return 0


if __name__ == "__main__":
    sys.exit(main())
